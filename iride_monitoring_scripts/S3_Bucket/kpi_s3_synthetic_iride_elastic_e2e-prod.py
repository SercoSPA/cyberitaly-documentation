def create_log_entry(bucket_name, environment, status,
                     upload_ms=None, download_ms=None, delete_ms=None,
                     total_ms=None, error=None, object_key=None,
                     cleanup_required=False, cleanup_succeeded=None):
    now = datetime.now(timezone.utc)
    timestamp = now.strftime("%Y-%m-%dT%H:%M:%S.%f")[:-3] + "Z"
    entry = {
        "@timestamp": timestamp,
        "event_timestamp": timestamp,
        "bucket_name": bucket_name,
        "environment": environment,
        "platform": "iride",
        "service_provider_log": "iride_s3_synthetic",
        "response_status": status,
        "event_type": "kpi_s3_synthetic_probe",
        "hostname": hostname,
        "test_object_key": object_key or "",
        "test_payload_bytes": len(TEST_PAYLOAD),
        "cleanup_required": cleanup_required,
    }
    if cleanup_succeeded is not None:
        entry["cleanup_succeeded"] = cleanup_succeeded
    if upload_ms is not None:
        entry["upload_latency_ms"] = round(upload_ms, 2)
    if download_ms is not None:
        entry["download_latency_ms"] = round(download_ms, 2)
    if delete_ms is not None:
        entry["delete_latency_ms"] = round(delete_ms, 2)
    if total_ms is not None:
        entry["total_latency_ms"] = round(total_ms, 2)
    if error:
        entry["error_message"] = str(error)[:500]
    return entry


def write_log(log_entry):
    """Scrive su file locale e (se abilitato) indicizza su Elastic."""
    line = json.dumps(log_entry, ensure_ascii=False, separators=(',', ':'))
    with open(log_file, 'a') as f:
        f.write(line + '\n')

    if ELASTIC_ENABLED and es is not None:
        try:
            es.index(index=MONITORING_INDEX, body=log_entry)
        except Exception as e:
            logger.warning(f"[ES_FAIL] {type(e).__name__}: {e}")


def make_s3_client(credentials):
    return boto3.client(
        's3',
        **credentials,
        config=BotoConfig(read_timeout=30, connect_timeout=10, retries={'max_attempts': 1})
    )


def cleanup_orphans(s3, bucket_name):
    """Best-effort cleanup di vecchi file __monitoring/ orfani."""
    try:
        response = s3.list_objects_v2(Bucket=bucket_name, Prefix=MONITORING_PREFIX, MaxKeys=100)
        contents = response.get('Contents', [])
        if not contents:
            return 0

        now = datetime.now(timezone.utc)
        deleted = 0
        for obj in contents:
            age_hours = (now - obj['LastModified']).total_seconds() / 3600
            if age_hours > ORPHAN_AGE_HOURS:
                try:
                    s3.delete_object(Bucket=bucket_name, Key=obj['Key'])
                    deleted += 1
                    logger.info(f"[CLEANUP_ORPHAN] {bucket_name}: rimosso "
                                f"{obj['Key']} (age {age_hours:.1f}h)")
                except Exception as e:
                    logger.warning(f"[CLEANUP_FAIL] {obj['Key']}: {e}")
        return deleted
    except Exception as e:
        logger.warning(f"[CLEANUP_SKIP] {bucket_name}: {e}")
        return 0


