def probe_bucket(bucket_name, credentials, environment):
    timestamp_str = datetime.now(timezone.utc).strftime("%Y%m%d%H%M%S")
    unique_id = uuid.uuid4().hex[:12]
    object_key = f"{MONITORING_PREFIX}probe-{timestamp_str}-{unique_id}.txt"

    # Etichetta visiva per distinguere prod da e2etest nel log
    env_tag = "[PROD]" if environment == "prod" else "[E2E ]"
    logger.info(f"[PROBE] {env_tag} {bucket_name} → {object_key}")

    s3 = make_s3_client(credentials)
    upload_ms = download_ms = delete_ms = None
    uploaded = False
    delete_succeeded_in_main = False
    cleanup_succeeded = None
    overall_start = time.perf_counter()

    try:
        cleanup_orphans(s3, bucket_name)

        # --- UPLOAD ---
        t0 = time.perf_counter()
        s3.put_object(
            Bucket=bucket_name,
            Key=object_key,
            Body=TEST_PAYLOAD,
            ContentType='text/plain',
            Metadata={'purpose': 'synthetic-monitoring', 'safe-to-delete': 'true'}
        )
        upload_ms = (time.perf_counter() - t0) * 1000
        uploaded = True
        logger.info(f"  [UPLOAD]   ✓ {upload_ms:.2f} ms")

        # --- DOWNLOAD + integrity check ---
        t0 = time.perf_counter()
        response = s3.get_object(Bucket=bucket_name, Key=object_key)
        downloaded_body = response['Body'].read()
        download_ms = (time.perf_counter() - t0) * 1000

        if downloaded_body != TEST_PAYLOAD:
            logger.error(f"  [DOWNLOAD] ✗ integrity check FAILED")
            raise ValueError("Downloaded body mismatch — possibile corruption")
        logger.info(f"  [DOWNLOAD] ✓ {download_ms:.2f} ms (integrity OK)")

        # --- DELETE ---
        t0 = time.perf_counter()
        s3.delete_object(Bucket=bucket_name, Key=object_key)
        delete_ms = (time.perf_counter() - t0) * 1000
        uploaded = False
        delete_succeeded_in_main = True
        logger.info(f"  [DELETE]   ✓ {delete_ms:.2f} ms")

        # --- Esito complessivo ---
        total_ms = (time.perf_counter() - overall_start) * 1000
        if total_ms < 5000:
            status = "OK"
        elif total_ms < 15000:
            status = "SLOW"
        else:
            status = "FAIL"

        logger.info(f"[SALVATO] {bucket_name} status={status} total={total_ms:.2f}ms")
        entry = create_log_entry(
            bucket_name, environment, status,
            upload_ms=upload_ms, download_ms=download_ms,
            delete_ms=delete_ms, total_ms=total_ms,
            object_key=object_key,
            cleanup_required=False
        )
        write_log(entry)

    except ClientError as e:
        code = e.response.get('Error', {}).get('Code', '?')
        error_msg = f"{code}: {e}"
        logger.error(f"  [STEP_FAIL] {error_msg}")
        total_ms = (time.perf_counter() - overall_start) * 1000
        logger.info(f"[SALVATO] {bucket_name} status=FAIL total={total_ms:.2f}ms")
        entry = create_log_entry(
            bucket_name, environment, "FAIL",
            upload_ms=upload_ms, download_ms=download_ms,
            delete_ms=delete_ms, total_ms=total_ms,
            error=error_msg, object_key=object_key,
            cleanup_required=uploaded
        )
        write_log(entry)

    except Exception as e:
        error_msg = f"{type(e).__name__}: {e}"
        logger.error(f"  [STEP_FAIL] {error_msg}")
        total_ms = (time.perf_counter() - overall_start) * 1000
        logger.info(f"[SALVATO] {bucket_name} status=FAIL total={total_ms:.2f}ms")
        entry = create_log_entry(
            bucket_name, environment, "FAIL",
            upload_ms=upload_ms, download_ms=download_ms,
            delete_ms=delete_ms, total_ms=total_ms,
            error=error_msg, object_key=object_key,
            cleanup_required=uploaded
        )
        write_log(entry)

    finally:
        if uploaded:
            logger.warning(f"  [CLEANUP] tentativo finally su {object_key}...")
            try:
                s3.delete_object(Bucket=bucket_name, Key=object_key)
                cleanup_succeeded = True
                logger.info(f"  [CLEANUP] ✓ rimosso in finally")
            except Exception as e:
                cleanup_succeeded = False
                logger.error(f"  [CLEANUP] ✗ FAILED — orfano lasciato: {e}")
        elif delete_succeeded_in_main:
            logger.info(f"  [SUMMARY] upload/download/delete tutti OK — nessun residuo")


